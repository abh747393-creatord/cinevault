export function getCollectionBySlug(slug: string): FranchiseCollection | undefined {
  if (!slug) return undefined;
  const cleanSlug = slug.toLowerCase().trim();
  return FRANCHISE_COLLECTIONS.find((c) => c.slug.toLowerCase() === cleanSlug);
}

