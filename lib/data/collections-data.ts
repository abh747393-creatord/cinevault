export function getCollectionBySlug(slug: string): FranchiseCollection | undefined {
  return FRANCHISE_COLLECTIONS.find((c) => c.slug === slug || c.id === slug);
}

export function getCollectionsByCategory(category?: 'movies' | 'anime' | 'dramas'): FranchiseCollection[] {
  if (!category) return FRANCHISE_COLLECTIONS;
  return FRANCHISE_COLLECTIONS.filter((c) => c.category === category);
}

